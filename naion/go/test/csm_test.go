// nonceModes are the nonce modes every generic test runs with, together with
// the fixed overhead of their packets:
//
//	derived (compact): signature(64) | session_x25519_public_key(32) | mac(16) | ciphertext
//	random:            signature(64) | session_x25519_public_key(32) | nonce(24) | mac(16) | ciphertext
var nonceModes = []struct {
	name     string
	mode     int
	overhead int
}{
	{"derived_compact", naion.CSMNonceDerived, 112},
	{"random", naion.CSMNonceRandom, 136},
}

func assertEqual(t testing.TB, name string, got []byte, want []byte) {
	t.Helper()
	if !bytes.Equal(got, want) {
		t.Fatalf("%s mismatch:\n got  %x\n want %x", name, got, want)
	}
}

func useRandomProvider(t testing.TB, fn naion.RandomProvider) {
	t.Helper()
	prev := naion.GetRandomProvider()
	naion.SetRandomProvider(fn)
	t.Cleanup(func() { naion.SetRandomProvider(prev) })
}

func fixedRandom(value byte) naion.RandomProvider {
	return func(buf []byte) error {
		for i := range buf {
			buf[i] = value
		}
		return nil
	}
}

func bootstrapServerWithMode(t testing.TB, client *naion.CSMClient, server *naion.CSMServer, mode int) {
	t.Helper()
	packet, rc := client.EncryptWithNonceMode([]byte("bootstrap"), mode)
	if rc != naion.CSMOK {
		t.Fatalf("bootstrap client encrypt failed: %v", rc)
	}
	if _, rc := server.DecryptWithNonceMode(packet, mode); rc != naion.CSMOK {
		t.Fatalf("bootstrap server decrypt failed: %v", rc)
	}
}

func newCAPair(t testing.TB) (*naion.CSMCAClient, *naion.CSMCAServer) {
	t.Helper()
	caSeed := seed32(t, "0303030303030303030303030303030303030303030303030303030303030303")
	caPK, caSK, err := naion.SignEd25519SeedKeypair(&caSeed)
	if err != nil {
		t.Fatalf("ca keypair: %v", err)
	}
	ss := seed32(t, testServerSeedHex)
	serverPK, _, err := naion.SignEd25519SeedKeypair(&ss)
	if err != nil {
		t.Fatalf("server keypair: %v", err)
	}
	caSig, err := naion.SignEd25519Detached(serverPK[:], &caSK)
	if err != nil {
		t.Fatalf("ca signature: %v", err)
	}
	server, rc := naion.CSMCAServerCreate(&ss, &caSig)
	if rc != naion.CSMOK {
		t.Fatalf("CSMCAServerCreate failed: %v", rc)
	}
	m1, rc := server.HandshakeResponse()
	if rc != naion.CSMOK {
		t.Fatalf("handshake response failed: %v", rc)
	}
	cs := seed32(t, testClientSeedHex)
	client, rc := naion.CSMCAClientCreate(&cs, &caPK)
	if rc != naion.CSMOK {
		t.Fatalf("CSMCAClientCreate failed: %v", rc)
	}
	if rc := client.HandshakeVerify(m1[:]); rc != naion.CSMOK {
		t.Fatalf("handshake verify failed: %v", rc)
	}
	return client, server
}

func TestGoPacketBudgetPerNonceMode(t *testing.T) {
	if naion.CSMNonceDerived != 0 || naion.CSMNonceRandom != 1 {
		t.Fatalf("nonce mode constants: derived=%d random=%d", naion.CSMNonceDerived, naion.CSMNonceRandom)
	}
	if naion.CSMMaxUDPDatagramBytes != 1024 {
		t.Fatalf("CSMMaxUDPDatagramBytes = %d, want 1024", naion.CSMMaxUDPDatagramBytes)
	}
	// The plain names are the default (derived nonce, compact) budget.
	if naion.CSMPacketOverhead != 112 || naion.CSMMaxClientPayloadBytes != 880 || naion.CSMMaxServerPayloadBytes != 912 {
		t.Fatalf("default budget: overhead=%d client=%d server=%d, want 112/880/912",
			naion.CSMPacketOverhead, naion.CSMMaxClientPayloadBytes, naion.CSMMaxServerPayloadBytes)
	}
	// The CSMRandom* names are the random nonce budget.
	if naion.CSMRandomPacketOverhead != 136 || naion.CSMRandomMaxClientPayloadBytes != 856 ||
		naion.CSMRandomMaxServerPayloadBytes != 888 {
		t.Fatalf("random budget: overhead=%d client=%d server=%d, want 136/856/888",
			naion.CSMRandomPacketOverhead, naion.CSMRandomMaxClientPayloadBytes, naion.CSMRandomMaxServerPayloadBytes)
	}

	// Any mode other than CSMNonceDerived is the random mode.
	budgets := []struct {
		mode, nonceField, overhead, clientMax, serverMax int
	}{
		{naion.CSMNonceDerived, 0, 112, 880, 912},
		{naion.CSMNonceRandom, 24, 136, 856, 888},
		{7, 24, 136, 856, 888},
	}
	for _, b := range budgets {
		if got := naion.CSMNonceFieldBytes(b.mode); got != b.nonceField {
			t.Fatalf("CSMNonceFieldBytes(%d) = %d, want %d", b.mode, got, b.nonceField)
		}
		if got := naion.CSMPacketOverheadEx(b.mode); got != b.overhead {
			t.Fatalf("CSMPacketOverheadEx(%d) = %d, want %d", b.mode, got, b.overhead)
		}
		if got := naion.CSMMaxClientPayloadBytesEx(b.mode); got != b.clientMax {
			t.Fatalf("CSMMaxClientPayloadBytesEx(%d) = %d, want %d", b.mode, got, b.clientMax)
		}
		if got := naion.CSMMaxServerPayloadBytesEx(b.mode); got != b.serverMax {
			t.Fatalf("CSMMaxServerPayloadBytesEx(%d) = %d, want %d", b.mode, got, b.serverMax)
		}
		// A packet of exactly the fixed size cannot hold any plaintext:
		// the helpers answer 0, like naion.h.
		if got := naion.CSMClientDecryptMaxPlaintextSizeEx(b.overhead, b.mode); got != 0 {
			t.Fatalf("CSMClientDecryptMaxPlaintextSizeEx(%d, %d) = %d, want 0", b.overhead, b.mode, got)
		}
		if got := naion.CSMServerDecryptMaxPlaintextSizeEx(b.overhead+32, b.mode); got != 0 {
			t.Fatalf("CSMServerDecryptMaxPlaintextSizeEx(%d, %d) = %d, want 0", b.overhead+32, b.mode, got)
		}
		for _, n := range []int{1, 16, 840, 880, 912, 1024} {
			if got, want := naion.CSMClientEncryptSizeEx(n, b.mode), b.overhead+32+n; got != want {
				t.Fatalf("CSMClientEncryptSizeEx(%d, %d) = %d, want %d", n, b.mode, got, want)
			}
			if got, want := naion.CSMServerEncryptSizeEx(n, b.mode), b.overhead+n; got != want {
				t.Fatalf("CSMServerEncryptSizeEx(%d, %d) = %d, want %d", n, b.mode, got, want)
			}
			if got, want := naion.CSMCAClientEncryptSizeEx(n, b.mode), b.overhead+32+n; got != want {
				t.Fatalf("CSMCAClientEncryptSizeEx(%d, %d) = %d, want %d", n, b.mode, got, want)
			}
			if got, want := naion.CSMCAServerEncryptSizeEx(n, b.mode), b.overhead+n; got != want {
				t.Fatalf("CSMCAServerEncryptSizeEx(%d, %d) = %d, want %d", n, b.mode, got, want)
			}
			// The plaintext bound of a packet is its payload length: the client
			// public key of a client packet counts as fixed overhead.
			if got := naion.CSMClientDecryptMaxPlaintextSizeEx(b.overhead+n, b.mode); got != n {
				t.Fatalf("CSMClientDecryptMaxPlaintextSizeEx(%d, %d) = %d, want %d", b.overhead+n, b.mode, got, n)
			}
			if got := naion.CSMServerDecryptMaxPlaintextSizeEx(b.overhead+32+n, b.mode); got != n {
				t.Fatalf("CSMServerDecryptMaxPlaintextSizeEx(%d, %d) = %d, want %d", b.overhead+32+n, b.mode, got, n)
			}
		}
	}

	// The helpers without a mode argument are the derived mode, for CSM and CSM-CA.
	for n := 0; n <= naion.CSMMaxUDPDatagramBytes; n++ {
		if naion.CSMClientEncryptSize(n) != naion.CSMClientEncryptSizeEx(n, naion.CSMNonceDerived) ||
			naion.CSMServerEncryptSize(n) != naion.CSMServerEncryptSizeEx(n, naion.CSMNonceDerived) ||
			naion.CSMClientDecryptMaxPlaintextSize(n) != naion.CSMClientDecryptMaxPlaintextSizeEx(n, naion.CSMNonceDerived) ||
			naion.CSMServerDecryptMaxPlaintextSize(n) != naion.CSMServerDecryptMaxPlaintextSizeEx(n, naion.CSMNonceDerived) ||
			naion.CSMCAClientEncryptSize(n) != naion.CSMCAClientEncryptSizeEx(n, naion.CSMNonceDerived) ||
			naion.CSMCAServerEncryptSize(n) != naion.CSMCAServerEncryptSizeEx(n, naion.CSMNonceDerived) ||
			naion.CSMCAClientDecryptMaxPlaintextSize(n) != naion.CSMCAClientDecryptMaxPlaintextSizeEx(n, naion.CSMNonceDerived) ||
			naion.CSMCAServerDecryptMaxPlaintextSize(n) != naion.CSMCAServerDecryptMaxPlaintextSizeEx(n, naion.CSMNonceDerived) {
			t.Fatalf("the size helpers without a mode argument are not the derived mode at n=%d", n)
		}
	}
	// The compact packet leaves 24 more bytes for the payload than the random one.
	if naion.CSMMaxClientPayloadBytes-naion.CSMRandomMaxClientPayloadBytes != 24 ||
		naion.CSMMaxServerPayloadBytes-naion.CSMRandomMaxServerPayloadBytes != 24 {
		t.Fatal("compact payload limits are not 24 bytes above the random ones")
	}
}

// TestGoRandomNonceRoundTripSizes: random mode packets are 136 + 32 + n bytes
// (client) and 136 + n bytes (server) and round trip in both directions.
func TestGoRandomNonceRoundTripSizes(t *testing.T) {
	for _, size := range testSizes {
		size := size
		t.Run(fmt.Sprintf("size_%d", size), func(t *testing.T) {
			payload := testPayload(size)
			client, server := newPair(t)

			clientPacket, rc := client.EncryptWithNonceMode(payload, naion.CSMNonceRandom)
			if rc != naion.CSMOK {
				t.Fatalf("client encrypt failed: %v", rc)
			}
			if want := 136 + 32 + size; len(clientPacket) != want {
				t.Fatalf("client packet size %d, want %d", len(clientPacket), want)
			}
			if want := naion.CSMClientEncryptSizeEx(size, naion.CSMNonceRandom); len(clientPacket) != want {
				t.Fatalf("client packet size %d, want CSMClientEncryptSizeEx %d", len(clientPacket), want)
			}
			serverPlain, rc := server.DecryptWithNonceMode(clientPacket, naion.CSMNonceRandom)
			if rc != naion.CSMOK {
				t.Fatalf("server decrypt failed: %v", rc)
			}
			assertEqual(t, "client->server", serverPlain, payload)

			client, server = newPair(t)
			bootstrapServerWithMode(t, client, server, naion.CSMNonceRandom)
			serverPacket, rc := server.EncryptWithNonceMode(payload, naion.CSMNonceRandom)
			if rc != naion.CSMOK {
				t.Fatalf("server encrypt failed: %v", rc)
			}
			if want := 136 + size; len(serverPacket) != want {
				t.Fatalf("server packet size %d, want %d", len(serverPacket), want)
			}
			if want := naion.CSMServerEncryptSizeEx(size, naion.CSMNonceRandom); len(serverPacket) != want {
				t.Fatalf("server packet size %d, want CSMServerEncryptSizeEx %d", len(serverPacket), want)
			}
			clientPlain, rc := client.DecryptWithNonceMode(serverPacket, naion.CSMNonceRandom)
			if rc != naion.CSMOK {
				t.Fatalf("client decrypt failed: %v", rc)
			}
			assertEqual(t, "server->client", clientPlain, payload)
		})
	}
}

// TestGoDefaultIsDerivedNonceMode: Encrypt/Decrypt without a mode argument
// are nonce mode 0 and do not interoperate with random mode.
func TestGoDefaultIsDerivedNonceMode(t *testing.T) {
	client, server := newPair(t)
	payload := testPayload(80)

	c2s, rc := client.Encrypt(payload)
	if rc != naion.CSMOK {
		t.Fatalf("default client encrypt failed: %v", rc)
	}
	if want := 112 + 32 + len(payload); len(c2s) != want {
		t.Fatalf("default client packet size %d, want %d", len(c2s), want)
	}
	if pt, rc := server.DecryptWithNonceMode(c2s, naion.CSMNonceDerived); rc != naion.CSMOK {
		t.Fatalf("a default packet is not a derived mode packet: %v", rc)
	} else {
		assertEqual(t, "default packet as derived mode", pt, payload)
	}
	if _, rc := server.DecryptWithNonceMode(c2s, naion.CSMNonceRandom); rc == naion.CSMOK {
		t.Fatal("a default packet was opened as a random mode packet")
	}
	random, rc := client.EncryptWithNonceMode(payload, naion.CSMNonceRandom)
	if rc != naion.CSMOK {
		t.Fatalf("random mode client encrypt failed: %v", rc)
	}
	if want := 136 + 32 + len(payload); len(random) != want {
		t.Fatalf("random mode client packet size %d, want %d", len(random), want)
	}
	if _, rc := server.Decrypt(random); rc == naion.CSMOK {
		t.Fatal("a random mode packet was opened by the default decrypt")
	}
	if _, rc := server.DecryptWithNonceMode(random, naion.CSMNonceRandom); rc != naion.CSMOK {
		t.Fatalf("random mode packet with the right mode: %v", rc)
	}

	if _, rc := server.Decrypt(c2s); rc != naion.CSMOK {
		t.Fatalf("default server decrypt failed: %v", rc)
	}
	s2c, rc := server.Encrypt(payload)
	if rc != naion.CSMOK {
		t.Fatalf("default server encrypt failed: %v", rc)
	}
	if want := 112 + len(payload); len(s2c) != want {
		t.Fatalf("default server packet size %d, want %d", len(s2c), want)
	}
	if pt, rc := client.DecryptWithNonceMode(s2c, naion.CSMNonceDerived); rc != naion.CSMOK {
		t.Fatalf("a default reply is not a derived mode packet: %v", rc)
	} else {
		assertEqual(t, "default reply as derived mode", pt, payload)
	}
	if _, rc := client.DecryptWithNonceMode(s2c, naion.CSMNonceRandom); rc == naion.CSMOK {
		t.Fatal("a default reply was opened as a random mode packet")
	}
	s2cRandom, rc := server.EncryptWithNonceMode(payload, naion.CSMNonceRandom)
	if rc != naion.CSMOK {
		t.Fatalf("random mode server encrypt failed: %v", rc)
	}
	if want := 136 + len(payload); len(s2cRandom) != want {
		t.Fatalf("random mode server packet size %d, want %d", len(s2cRandom), want)
	}
	if _, rc := client.Decrypt(s2cRandom); rc == naion.CSMOK {
		t.Fatal("a random mode reply was opened by the default decrypt")
	}
}

// TestGoNonceModeMismatch: the sender and the receiver must use the same
// nonce mode. A mismatch fails and does not teach the server the client key.
func TestGoNonceModeMismatch(t *testing.T) {
	client, server := newPair(t)
	payload := testPayload(80)
	compact, rc := client.Encrypt(payload)
	if rc != naion.CSMOK {
		t.Fatalf("client encrypt failed: %v", rc)
	}
	random, rc := client.EncryptWithNonceMode(payload, naion.CSMNonceRandom)
	if rc != naion.CSMOK {
		t.Fatalf("client encrypt failed: %v", rc)
	}

	// client -> server
	if _, rc := server.DecryptWithNonceMode(compact, naion.CSMNonceRandom); rc != naion.CSMErrCrypto {
		t.Fatalf("compact packet opened as random mode: got %v, want %v", rc, naion.CSMErrCrypto)
	}
	if _, rc := server.Decrypt(random); rc != naion.CSMErrCrypto {
		t.Fatalf("random mode packet opened as compact: got %v, want %v", rc, naion.CSMErrCrypto)
	}
	if server.ClientPublicKeyInitialized {
		t.Fatal("the server learnt the client key from a packet of another nonce mode")
	}
	// The packets are intact: with the right mode they open.
	if pt, rc := server.Decrypt(compact); rc != naion.CSMOK {
		t.Fatalf("compact packet with the right mode failed: %v", rc)
	} else {
		assertEqual(t, "compact packet with the right mode", pt, payload)
	}
	if !server.ClientPublicKeyInitialized || server.ClientEdPublicKey != client.EdPublicKey {
		t.Fatal("the server did not learn the client key from a valid packet")
	}
	if pt, rc := server.DecryptWithNonceMode(random, naion.CSMNonceRandom); rc != naion.CSMOK {
		t.Fatalf("random mode packet with the right mode failed: %v", rc)
	} else {
		assertEqual(t, "random mode packet with the right mode", pt, payload)
	}

	// server -> client
	replyCompact, rc := server.Encrypt(payload)
	if rc != naion.CSMOK {
		t.Fatalf("server encrypt failed: %v", rc)
	}
	replyRandom, rc := server.EncryptWithNonceMode(payload, naion.CSMNonceRandom)
	if rc != naion.CSMOK {
		t.Fatalf("server encrypt failed: %v", rc)
	}
	if _, rc := client.DecryptWithNonceMode(replyCompact, naion.CSMNonceRandom); rc != naion.CSMErrCrypto {
		t.Fatalf("compact reply opened as random mode: got %v, want %v", rc, naion.CSMErrCrypto)
	}
	if _, rc := client.Decrypt(replyRandom); rc != naion.CSMErrCrypto {
		t.Fatalf("random mode reply opened as compact: got %v, want %v", rc, naion.CSMErrCrypto)
	}
	if pt, rc := client.Decrypt(replyCompact); rc != naion.CSMOK {
		t.Fatalf("compact reply with the right mode failed: %v", rc)
	} else {
		assertEqual(t, "compact reply with the right mode", pt, payload)
	}
	if pt, rc := client.DecryptWithNonceMode(replyRandom, naion.CSMNonceRandom); rc != naion.CSMOK {
		t.Fatalf("random mode reply with the right mode failed: %v", rc)
	} else {
		assertEqual(t, "random mode reply with the right mode", pt, payload)
	}
}

// TestGoCompactTamperEveryField flips bytes in every field of a compact
// (default mode) packet: signature, session public key, mac and ciphertext.
func TestGoCompactTamperEveryField(t *testing.T) {
	client, server := newPair(t)
	frame, rc := client.Encrypt(testPayload(64))
	if rc != naion.CSMOK {
		t.Fatalf("client encrypt failed: %v", rc)
	}
	// signature(64) | session_x25519_public_key(64:96) | mac(96:112) | ciphertext(112:)
	fields := []struct {
		name    string
		offsets []int
		want    naion.CSMError
	}{
		{"signature", []int{0, 32, 63}, naion.CSMErrVerifyFailed},
		{"session_x25519_public_key", []int{64, 80, 95}, naion.CSMErrCrypto},
		{"mac", []int{96, 104, 111}, naion.CSMErrCrypto},
		{"ciphertext", []int{112, (112 + len(frame)) / 2, len(frame) - 1}, naion.CSMErrCrypto},
	}
	for _, field := range fields {
		for _, offset := range field.offsets {
			tampered := append([]byte{}, frame...)
			tampered[offset] ^= 0x01
			if _, rc := server.Decrypt(tampered); rc != field.want {
				t.Fatalf("%s byte %d tampered: got %v, want %v", field.name, offset, rc, field.want)
			}
			if server.ClientPublicKeyInitialized {
				t.Fatalf("%s byte %d tampered: the server learnt a client key", field.name, offset)
			}
		}
	}
	// Every single byte of both packet types matters, in both modes.
	for _, nm := range nonceModes {
		client, server := newPair(t)
		payload := testPayload(37)
		c2s, rc := client.EncryptWithNonceMode(payload, nm.mode)
		if rc != naion.CSMOK {
			t.Fatalf("%s client encrypt failed: %v", nm.name, rc)
		}
		for i := range c2s {
			bad := append([]byte{}, c2s...)
			bad[i] ^= 0x80
			if _, rc := server.DecryptWithNonceMode(bad, nm.mode); rc != naion.CSMErrCrypto && rc != naion.CSMErrVerifyFailed {
				t.Fatalf("%s: client packet byte %d tampered: got %v, want Crypto or VerifyFailed", nm.name, i, rc)
			}
		}
		if pt, rc := server.DecryptWithNonceMode(c2s, nm.mode); rc != naion.CSMOK {
			t.Fatalf("%s: untampered client packet failed: %v", nm.name, rc)
		} else {
			assertEqual(t, nm.name+" untampered client packet", pt, payload)
		}
		s2c, rc := server.EncryptWithNonceMode(payload, nm.mode)
		if rc != naion.CSMOK {
			t.Fatalf("%s server encrypt failed: %v", nm.name, rc)
		}
		for i := range s2c {
			bad := append([]byte{}, s2c...)
			bad[i] ^= 0x80
			// The client verifies the server signature before opening the packet.
			if _, rc := client.DecryptWithNonceMode(bad, nm.mode); rc != naion.CSMErrVerifyFailed {
				t.Fatalf("%s: server packet byte %d tampered: got %v, want VerifyFailed", nm.name, i, rc)
			}
		}
	}
}

// TestGoPayloadLimits: the largest payload of each nonce mode fills a
// CSMMaxUDPDatagramBytes datagram exactly and round trips.
func TestGoPayloadLimits(t *testing.T) {
	limits := []struct {
		mode       int
		clientSize int
		serverSize int
	}{
		{naion.CSMNonceDerived, 880, 912},
		{naion.CSMNonceRandom, 856, 888},
	}
	for _, l := range limits {
		client, server := newPair(t)

		c2sPayload := testPayload(l.clientSize)
		c2s, rc := client.EncryptWithNonceMode(c2sPayload, l.mode)
		if rc != naion.CSMOK {
			t.Fatalf("mode %d: client encrypt of %d bytes failed: %v", l.mode, l.clientSize, rc)
		}
		if len(c2s) != naion.CSMMaxUDPDatagramBytes {
			t.Fatalf("mode %d: client packet size %d, want a full %d byte datagram",
				l.mode, len(c2s), naion.CSMMaxUDPDatagramBytes)
		}
		if pt, rc := server.DecryptWithNonceMode(c2s, l.mode); rc != naion.CSMOK {
			t.Fatalf("mode %d: server decrypt of %d bytes failed: %v", l.mode, l.clientSize, rc)
		} else {
			assertEqual(t, "largest client payload", pt, c2sPayload)
		}

		s2cPayload := testPayload(l.serverSize)
		s2c, rc := server.EncryptWithNonceMode(s2cPayload, l.mode)
		if rc != naion.CSMOK {
			t.Fatalf("mode %d: server encrypt of %d bytes failed: %v", l.mode, l.serverSize, rc)
		}
		if len(s2c) != naion.CSMMaxUDPDatagramBytes {
			t.Fatalf("mode %d: server packet size %d, want a full %d byte datagram",
				l.mode, len(s2c), naion.CSMMaxUDPDatagramBytes)
		}
		if pt, rc := client.DecryptWithNonceMode(s2c, l.mode); rc != naion.CSMOK {
			t.Fatalf("mode %d: client decrypt of %d bytes failed: %v", l.mode, l.serverSize, rc)
		} else {
			assertEqual(t, "largest server payload", pt, s2cPayload)
		}

		// One more payload byte does not fit into the datagram.
		if got := naion.CSMClientEncryptSizeEx(l.clientSize+1, l.mode); got != naion.CSMMaxUDPDatagramBytes+1 {
			t.Fatalf("mode %d: CSMClientEncryptSizeEx(%d) = %d, want %d",
				l.mode, l.clientSize+1, got, naion.CSMMaxUDPDatagramBytes+1)
		}
		if got := naion.CSMServerEncryptSizeEx(l.serverSize+1, l.mode); got != naion.CSMMaxUDPDatagramBytes+1 {
			t.Fatalf("mode %d: CSMServerEncryptSizeEx(%d) = %d, want %d",
				l.mode, l.serverSize+1, got, naion.CSMMaxUDPDatagramBytes+1)
		}
	}
}

// TestGoCrossLanguageVectors reproduces the packets of PROTOCOL.md byte for
// byte: fixed seeds, a random provider that answers 0x5A, 16-byte payload.
func TestGoCrossLanguageVectors(t *testing.T) {
	useRandomProvider(t, fixedRandom(0x5A))
	var cseed, sseed [32]byte
	for i := range cseed {
		cseed[i] = 0x01
		sseed[i] = 0x02
	}
	server, rc := naion.CSMServerCreate(&sseed)
	if rc != naion.CSMOK {
		t.Fatalf("CSMServerCreate failed: %v", rc)
	}
	spk := server.EdPublicKey
	client, rc := naion.CSMClientCreate(&cseed, &spk)
	if rc != naion.CSMOK {
		t.Fatalf("CSMClientCreate failed: %v", rc)
	}
	assertEqual(t, "server_ed_pk", spk[:], mustHex(t, csmVecServerEdPKHex))
	assertEqual(t, "client_ed_pk", client.EdPublicKey[:], mustHex(t, csmVecClientEdPKHex))

	payload := make([]byte, 16)
	for i := range payload {
		payload[i] = byte(i)
	}

	// nonce_mode = 0 (derived, compact): 160 and 128 bytes.
	c2sCompact, rc := client.Encrypt(payload)
	if rc != naion.CSMOK {
		t.Fatalf("client encrypt failed: %v", rc)
	}
	if len(c2sCompact) != 160 {
		t.Fatalf("c2s_compact is %d bytes, want 160", len(c2sCompact))
	}
	assertEqual(t, "c2s_compact", c2sCompact, mustHex(t, csmVecC2SCompactHex))
	if pt, rc := server.Decrypt(c2sCompact); rc != naion.CSMOK {
		t.Fatalf("server decrypt c2s_compact failed: %v", rc)
	} else {
		assertEqual(t, "c2s_compact opened", pt, payload)
	}
	s2cCompact, rc := server.Encrypt(payload)
	if rc != naion.CSMOK {
		t.Fatalf("server encrypt failed: %v", rc)
	}
	if len(s2cCompact) != 128 {
		t.Fatalf("s2c_compact is %d bytes, want 128", len(s2cCompact))
	}
	assertEqual(t, "s2c_compact", s2cCompact, mustHex(t, csmVecS2CCompactHex))
	if pt, rc := client.Decrypt(s2cCompact); rc != naion.CSMOK {
		t.Fatalf("client decrypt s2c_compact failed: %v", rc)
	} else {
		assertEqual(t, "s2c_compact opened", pt, payload)
	}

	// nonce_mode != 0 (random): 184 and 152 bytes.
	c2sRandom, rc := client.EncryptWithNonceMode(payload, naion.CSMNonceRandom)
	if rc != naion.CSMOK {
		t.Fatalf("client encrypt failed: %v", rc)
	}
	if len(c2sRandom) != 184 {
		t.Fatalf("c2s_random is %d bytes, want 184", len(c2sRandom))
	}
	assertEqual(t, "c2s_random", c2sRandom, mustHex(t, csmVecC2SRandomHex))
	if pt, rc := server.DecryptWithNonceMode(c2sRandom, naion.CSMNonceRandom); rc != naion.CSMOK {
		t.Fatalf("server decrypt c2s_random failed: %v", rc)
	} else {
		assertEqual(t, "c2s_random opened", pt, payload)
	}
	s2cRandom, rc := server.EncryptWithNonceMode(payload, naion.CSMNonceRandom)
	if rc != naion.CSMOK {
		t.Fatalf("server encrypt failed: %v", rc)
	}
	if len(s2cRandom) != 152 {
		t.Fatalf("s2c_random is %d bytes, want 152", len(s2cRandom))
	}
	assertEqual(t, "s2c_random", s2cRandom, mustHex(t, csmVecS2CRandomHex))
	if pt, rc := client.DecryptWithNonceMode(s2cRandom, naion.CSMNonceRandom); rc != naion.CSMOK {
		t.Fatalf("client decrypt s2c_random failed: %v", rc)
	} else {
		assertEqual(t, "s2c_random opened", pt, payload)
	}

	// A random mode packet is the compact packet of the same key pair plus its nonce field.
	if len(c2sRandom)-len(c2sCompact) != 24 || len(s2cRandom)-len(s2cCompact) != 24 {
		t.Fatal("random mode vectors are not 24 bytes longer than the compact ones")
	}
	for _, p := range [][]byte{c2sCompact, s2cCompact, c2sRandom, s2cRandom} {
		assertEqual(t, "session_x25519_public_key", p[64:96], c2sCompact[64:96])
	}
	assertEqual(t, "c2s_random nonce", c2sRandom[96:120], bytes.Repeat([]byte{0x5A}, 24))
	assertEqual(t, "s2c_random nonce", s2cRandom[96:120], bytes.Repeat([]byte{0x5A}, 24))
}

// TestGoCARoundTripBothNonceModes: post-handshake CSM-CA traffic round trips
// in both nonce modes and uses the Layer 3 packet sizes.
func TestGoCARoundTripBothNonceModes(t *testing.T) {
	for _, nm := range nonceModes {
		client, server := newCAPair(t)
		other := naion.CSMNonceRandom
		if nm.mode == naion.CSMNonceRandom {
			other = naion.CSMNonceDerived
		}
		payload := testPayload(120)

		c2s, rc := client.EncryptWithNonceMode(payload, nm.mode)
		if rc != naion.CSMOK {
			t.Fatalf("%s: ca client encrypt failed: %v", nm.name, rc)
		}
		if want := nm.overhead + 32 + len(payload); len(c2s) != want {
			t.Fatalf("%s: ca client packet size %d, want %d", nm.name, len(c2s), want)
		}
		if want := naion.CSMCAClientEncryptSizeEx(len(payload), nm.mode); len(c2s) != want {
			t.Fatalf("%s: ca client packet size %d, want CSMCAClientEncryptSizeEx %d", nm.name, len(c2s), want)
		}
		if _, rc := server.DecryptWithNonceMode(c2s, other); rc == naion.CSMOK {
			t.Fatalf("%s: ca client packet opened with another nonce mode", nm.name)
		}
		if server.ClientKeyVerified {
			t.Fatalf("%s: the ca server learnt the client key from a packet of another nonce mode", nm.name)
		}
		if pt, rc := server.DecryptWithNonceMode(c2s, nm.mode); rc != naion.CSMOK {
			t.Fatalf("%s: ca server decrypt failed: %v", nm.name, rc)
		} else {
			assertEqual(t, nm.name+" ca client->server", pt, payload)
		}
		if !server.ClientKeyVerified || server.ClientEdPublicKey != client.EdPublicKey {
			t.Fatalf("%s: the ca server did not learn the client key", nm.name)
		}

		s2c, rc := server.EncryptWithNonceMode(payload, nm.mode)
		if rc != naion.CSMOK {
			t.Fatalf("%s: ca server encrypt failed: %v", nm.name, rc)
		}
		if want := nm.overhead + len(payload); len(s2c) != want {
			t.Fatalf("%s: ca server packet size %d, want %d", nm.name, len(s2c), want)
		}
		if want := naion.CSMCAServerEncryptSizeEx(len(payload), nm.mode); len(s2c) != want {
			t.Fatalf("%s: ca server packet size %d, want CSMCAServerEncryptSizeEx %d", nm.name, len(s2c), want)
		}
		if _, rc := client.DecryptWithNonceMode(s2c, other); rc == naion.CSMOK {
			t.Fatalf("%s: ca server packet opened with another nonce mode", nm.name)
		}
		if pt, rc := client.DecryptWithNonceMode(s2c, nm.mode); rc != naion.CSMOK {
			t.Fatalf("%s: ca client decrypt failed: %v", nm.name, rc)
		} else {
			assertEqual(t, nm.name+" ca server->client", pt, payload)
		}

		// The CSM-CA default is the derived mode and shares the Layer 3 vectors.
		if nm.mode == naion.CSMNonceDerived {
			defaultPacket, rc := client.Encrypt(payload)
			if rc != naion.CSMOK || len(defaultPacket) != len(c2s) {
				t.Fatalf("ca default client packet: rc=%v len=%d", rc, len(defaultPacket))
			}
			if pt, rc := server.Decrypt(defaultPacket); rc != naion.CSMOK {
				t.Fatalf("ca default server decrypt: rc=%v", rc)
			} else {
				assertEqual(t, "ca default client->server", pt, payload)
			}
			defaultReply, rc := server.Encrypt(payload)
			if rc != naion.CSMOK || len(defaultReply) != len(s2c) {
				t.Fatalf("ca default server packet: rc=%v len=%d", rc, len(defaultReply))
			}
			if pt, rc := client.Decrypt(defaultReply); rc != naion.CSMOK {
				t.Fatalf("ca default client decrypt: rc=%v", rc)
			} else {
				assertEqual(t, "ca default server->client", pt, payload)
			}
		}
	}

	// With the inputs of the cross-language vectors the CSM-CA packets are the
	// Layer 3 vectors: the handshake only establishes the server key.
	useRandomProvider(t, fixedRandom(0x5A))
	var caSeed [32]byte
	for i := range caSeed {
		caSeed[i] = 0x03
	}
	caPK, caSK, err := naion.SignEd25519SeedKeypair(&caSeed)
	if err != nil {
		t.Fatalf("ca keypair: %v", err)
	}
	var cseed, sseed [32]byte
	for i := range cseed {
		cseed[i] = 0x01
		sseed[i] = 0x02
	}
	serverPK, _, err := naion.SignEd25519SeedKeypair(&sseed)
	if err != nil {
		t.Fatalf("server keypair: %v", err)
	}
	caSig, err := naion.SignEd25519Detached(serverPK[:], &caSK)
	if err != nil {
		t.Fatalf("ca signature: %v", err)
	}
	server, rc := naion.CSMCAServerCreate(&sseed, &caSig)
	if rc != naion.CSMOK {
		t.Fatalf("CSMCAServerCreate failed: %v", rc)
	}
	m1, rc := server.HandshakeResponse()
	if rc != naion.CSMOK {
		t.Fatalf("handshake response failed: %v", rc)
	}
	client, rc := naion.CSMCAClientCreate(&cseed, &caPK)
	if rc != naion.CSMOK {
		t.Fatalf("CSMCAClientCreate failed: %v", rc)
	}
	if rc := client.HandshakeVerify(m1[:]); rc != naion.CSMOK {
		t.Fatalf("handshake verify failed: %v", rc)
	}
	payload := make([]byte, 16)
	for i := range payload {
		payload[i] = byte(i)
	}
	c2s, rc := client.Encrypt(payload)
	if rc != naion.CSMOK {
		t.Fatalf("ca client encrypt failed: %v", rc)
	}
	assertEqual(t, "ca c2s_compact", c2s, mustHex(t, csmVecC2SCompactHex))
	// The server learns the client key from the first packet it opens.
	if pt, rc := server.Decrypt(c2s); rc != naion.CSMOK {
		t.Fatalf("ca server decrypt failed: %v", rc)
	} else {
		assertEqual(t, "ca c2s_compact opened", pt, payload)
	}
	s2c, rc := server.Encrypt(payload)
	if rc != naion.CSMOK {
		t.Fatalf("ca server encrypt failed: %v", rc)
	}
	assertEqual(t, "ca s2c_compact", s2c, mustHex(t, csmVecS2CCompactHex))
	if pt, rc := client.Decrypt(s2c); rc != naion.CSMOK {
		t.Fatalf("ca client decrypt failed: %v", rc)
	} else {
		assertEqual(t, "ca s2c_compact opened", pt, payload)
	}
	c2sRandom, rc := client.EncryptWithNonceMode(payload, naion.CSMNonceRandom)
	if rc != naion.CSMOK {
		t.Fatalf("ca client encrypt failed: %v", rc)
	}
	assertEqual(t, "ca c2s_random", c2sRandom, mustHex(t, csmVecC2SRandomHex))
	if pt, rc := server.DecryptWithNonceMode(c2sRandom, naion.CSMNonceRandom); rc != naion.CSMOK {
		t.Fatalf("ca server decrypt failed: %v", rc)
	} else {
		assertEqual(t, "ca c2s_random opened", pt, payload)
	}
	s2cRandom, rc := server.EncryptWithNonceMode(payload, naion.CSMNonceRandom)
	if rc != naion.CSMOK {
		t.Fatalf("ca server encrypt failed: %v", rc)
	}
	assertEqual(t, "ca s2c_random", s2cRandom, mustHex(t, csmVecS2CRandomHex))
	if pt, rc := client.DecryptWithNonceMode(s2cRandom, naion.CSMNonceRandom); rc != naion.CSMOK {
		t.Fatalf("ca client decrypt failed: %v", rc)
	} else {
		assertEqual(t, "ca s2c_random opened", pt, payload)
	}
}

